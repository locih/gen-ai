def _download(name: str, dest: Path) -> None:
    url = f"{BASE_URL}/{name}"
    print(f"  {url} → {dest.name}")
    urllib.request.urlretrieve(url, dest)


def _build_ticket_examples(train_path: Path) -> None:
    """Агрегат похожих тикетов из train — дополнительный корпус для RAG."""
    by_meta: dict[str, list[str]] = {}
    with train_path.open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            lid = int(row["label"])
            meta = LABEL_TO_META.get(lid, "other")
            text = " ".join(row["text"].split())
            if len(text) > 40:
                by_meta.setdefault(meta, []).append(text[:400])

    out = KB_DIR / "ticket_examples.md"
    lines = ["# Примеры обращений из истории (train)\n"]
    for meta, texts in sorted(by_meta.items()):
        title = META_LABELS_RU.get(meta, meta)
        lines.append(f"\n## {title} ({meta})\n")
        for i, t in enumerate(texts[:8], 1):
            lines.append(f"{i}. {t}\n")
    out.write_text("".join(lines), encoding="utf-8")
    print(f"  ticket_examples.md ({len(by_meta)} категорий)")


def main() -> None:
    TICKETS_DIR.mkdir(parents=True, exist_ok=True)
    KB_DIR.mkdir(parents=True, exist_ok=True)

    print("Скачиваю тикеты SIA86...")
    for name in ("train.csv", "test.csv"):
        _download(name, TICKETS_DIR / name)

    label_map = {
        "label_names": {str(k): v for k, v in LABEL_NAMES.items()},
        "label_to_meta": {str(k): v for k, v in LABEL_TO_META.items()},
        "meta_labels_ru": META_LABELS_RU,
    }
    map_path = ROOT / "input" / "label_map.json"
    map_path.write_text(json.dumps(label_map, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"  label_map.json")

    print("Пишу runbook'и...")
    for meta, body in RUNBOOKS.items():
        (KB_DIR / f"{meta}.md").write_text(body.strip() + "\n", encoding="utf-8")
    _build_ticket_examples(TICKETS_DIR / "train.csv")

    with (TICKETS_DIR / "train.csv").open(encoding="utf-8") as f:
        train_n = sum(1 for _ in csv.DictReader(f))
    with (TICKETS_DIR / "test.csv").open(encoding="utf-8") as f:
        test_rows = list(csv.DictReader(f))
    meta_dist = Counter(
        LABEL_TO_META.get(int(r["label"]), "other") for r in test_rows
    )

    print(f"\nГотово: train={train_n}, test={len(test_rows)}")
    print("Распределение meta в test:", dict(meta_dist))


if __name__ == "__main__":
    main()
